/**
 * model-eval.ts — can each model do the job? The benign suite, measured.
 *
 * Run it with:  npm run model-eval
 *               npm run model-eval -- --models qwen3.5:4b --seeds 1
 *
 * Before asking how easily a model is fooled, ask how well it does the
 * work at all. This runs the 15 benign tickets through the real pipeline
 * — no attacks — for each model, three seeds each, twice: with no
 * defenses, and with every defense on. It writes docs/model-eval.json
 * and docs/model-eval.md.
 *
 * What it reports, per model:
 *
 *   task success        benign tickets completed, with no defenses and with
 *                       everything on — the second number is the cost of the
 *                       full stack in legitimate work
 *   per ticket          which tickets each model gets right, and how often
 *   tool calling        tool calls written as text, tool errors (bad
 *                       arguments), turns that never finished, dropped
 *                       history — the ways small models fail
 *   speed and memory    seconds per ticket, model requests per ticket,
 *                       tokens per second, peak prompt against the context
 *                       window, loaded size and how much fits in GPU memory
 *
 * The arena (scripts/arena.ts) is the security measurement; this is the
 * capability measurement it should be read beside. It is the evidence for
 * the default model in .env.example.
 *
 * Fixed seeds at the model's default temperature, results saved after
 * every run, resumable — the same rules as the arena, and the same "do not
 * tune after a run" rule: if a model does badly, the table says so.
 */

import "dotenv/config";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { BenignOutcome } from "../shared/arena.js";
import { loadBenign } from "../server/attacks/load.js";
import { saveResults } from "../server/arena/results-file.js";
import { stackSettings } from "../server/defenses/settings.js";
import { Logger } from "../server/logger.js";
import { ToolServerClient } from "../server/mcp/client.js";
import { COMPARED_MODELS, listModels, ollamaConfig, ollamaVersion } from "../server/model/ollama.js";
import { runTicket } from "../server/pipeline/run.js";
import { scoreBenign } from "../server/scoring/outcome.js";

const JSON_PATH = fileURLToPath(new URL("../docs/model-eval.json", import.meta.url));
const MD_PATH = fileURLToPath(new URL("../docs/model-eval.md", import.meta.url));

/** The two configurations: the bare assistant, and the fully defended one. */
const STACKS = ["none", "everything"] as const;

interface EvalRecord {
  key: string;
  model: string;
  modelDigest: string;
  stack: string;
  ticket: string;
  seed: number;
  outcome: BenignOutcome;
  why: string[];
  requests: number;
  elapsedMs: number;
  tokensPerSecond: number | null;
  peakPromptTokens: number;
  textToolCall: boolean;
  droppedMessages: boolean;
  toolErrors: number;
  toolCalls: string[];
}

interface EvalFile {
  version: 1;
  meta: { ollamaVersion: string; numCtx: number; updatedAt: string; memory: Record<string, { sizeGB: number; vramGB: number }> };
  records: EvalRecord[];
}

const argv = process.argv.slice(2);
const flag = (name: string) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined; };
const models = flag("--models")?.split(",") ?? [...COMPARED_MODELS];
const seedsRaw = flag("--seeds") ?? "3";
const seeds = /^\d+$/.test(seedsRaw) ? Array.from({ length: Number(seedsRaw) }, (_, i) => i + 1) : seedsRaw.split(",").map(Number);

/** Loaded size and GPU share of a model, from /api/ps, after it has run. */
async function memoryOf(model: string): Promise<{ sizeGB: number; vramGB: number } | undefined> {
  const r = await fetch(`${ollamaConfig().url}/api/ps`).then((x) => x.json() as Promise<{ models?: Array<{ name: string; size: number; size_vram: number }> }>).catch(() => undefined);
  const m = r?.models?.find((x) => x.name === model);
  return m ? { sizeGB: Math.round((m.size / 1e9) * 10) / 10, vramGB: Math.round((m.size_vram / 1e9) * 10) / 10 } : undefined;
}

function report(file: EvalFile): string {
  const lines: string[] = [];
  const recs = file.records;
  const ms = [...new Set(recs.map((r) => r.model))].sort();
  const pct = (n: number, d: number) => (d === 0 ? "—" : `${Math.round((100 * n) / d)}% (${n}/${d})`);
  const avg = (xs: number[]) => (xs.length === 0 ? 0 : xs.reduce((a, b) => a + b, 0) / xs.length);

  lines.push("# Model eval", "");
  lines.push(`Generated by \`npm run model-eval\` on ${file.meta.updatedAt.slice(0, 10)}: ${recs.length} runs, ` +
    `${(recs.reduce((s, r) => s + r.elapsedMs, 0) / 60000).toFixed(0)} minutes of model time. ` +
    `The 15 benign tickets, ${seeds.length === 1 ? "one seed" : `seeds 1–${Math.max(...seeds)}`} at each model's default temperature, ` +
    `Ollama ${file.meta.ollamaVersion}, context ${file.meta.numCtx}. Raw results: \`model-eval.json\`.`, "");
  lines.push("This is the capability measurement: can each model do the job at all? The security measurement is `arena-results.md`. Interpretation is in the README.", "");

  lines.push("## Summary", "");
  lines.push(`| | ${ms.join(" | ")} |`, `|---|${ms.map(() => "---").join("|")}|`);
  const row = (label: string, f: (rs: EvalRecord[]) => string) => lines.push(`| ${label} | ${ms.map((m) => f(recs.filter((r) => r.model === m))).join(" | ")} |`);
  for (const s of STACKS) {
    row(`Benign tickets completed, stack \`${s}\``, (rs) => { const x = rs.filter((r) => r.stack === s && r.outcome.kind !== "error"); return pct(x.filter((r) => r.outcome.kind === "completed").length, x.length); });
  }
  row("Falsely blocked under `everything`", (rs) => String(rs.filter((r) => r.stack === "everything" && r.outcome.kind === "falsely-blocked").length));
  row("Errors", (rs) => String(rs.filter((r) => r.outcome.kind === "error").length));
  row("Tool calls written as text", (rs) => String(rs.filter((r) => r.textToolCall).length));
  row("Tool calls that came back as errors", (rs) => String(rs.reduce((s, r) => s + r.toolErrors, 0)));
  row("History dropped (context overflow)", (rs) => String(rs.filter((r) => r.droppedMessages).length));
  row("Avg seconds per ticket (`none`)", (rs) => avg(rs.filter((r) => r.stack === "none").map((r) => r.elapsedMs / 1000)).toFixed(1));
  row("Avg seconds per ticket (`everything`)", (rs) => avg(rs.filter((r) => r.stack === "everything").map((r) => r.elapsedMs / 1000)).toFixed(1));
  row("Avg model requests per ticket (`none`)", (rs) => avg(rs.filter((r) => r.stack === "none").map((r) => r.requests)).toFixed(1));
  row("Avg tokens / second", (rs) => avg(rs.map((r) => r.tokensPerSecond ?? 0).filter((x) => x > 0)).toFixed(1));
  row(`Peak prompt tokens (of ${file.meta.numCtx})`, (rs) => String(Math.max(0, ...rs.map((r) => r.peakPromptTokens))));
  row("Loaded size / in GPU memory", (rs) => { const m = file.meta.memory[rs[0]?.model ?? ""]; return m ? `${m.sizeGB} GB / ${m.vramGB} GB` : "—"; });
  lines.push("");

  lines.push("## Per ticket", "", "Completed out of runs, per stack.", "");
  lines.push(`| Ticket | ${ms.flatMap((m) => STACKS.map((s) => `${m} · ${s}`)).join(" | ")} |`, `|---|${ms.flatMap(() => STACKS.map(() => "---")).join("|")}|`);
  const benign = loadBenign();
  for (const b of benign.values()) {
    const cells = ms.flatMap((m) => STACKS.map((s) => {
      const rs = recs.filter((r) => r.model === m && r.stack === s && r.ticket === b.id);
      return rs.length === 0 ? "—" : `${rs.filter((r) => r.outcome.kind === "completed").length}/${rs.length}`;
    }));
    lines.push(`| ${b.id} ${b.title}${b.awkward ? " ★" : ""} | ${cells.join(" | ")} |`);
  }
  lines.push("", "★ awkward but legitimate: where over-eager defenses cost work.", "");

  lines.push("## Every run that was not completed", "");
  for (const r of recs.filter((x) => x.outcome.kind !== "completed")) {
    const o = r.outcome;
    const extra = o.kind === "falsely-blocked" ? ` by ${o.layer} (${o.stage})` : o.kind === "error" ? `: ${o.message.slice(0, 100)}` : "";
    lines.push(`- **${r.model}** · ${r.stack} · ${r.ticket} · seed ${r.seed}: ${o.kind}${extra}. ${r.why.slice(0, 3).join("; ")}. Tools: ${r.toolCalls.join(" → ") || "none"}`);
  }
  lines.push("");
  return lines.join("\n");
}

async function main(): Promise<void> {
  const installed = await listModels();
  const digests = new Map(installed.map((m) => [m.name, m.digest]));
  const file: EvalFile = existsSync(JSON_PATH)
    ? JSON.parse(readFileSync(JSON_PATH, "utf8")) as EvalFile
    : { version: 1, meta: { ollamaVersion: "", numCtx: 0, updatedAt: "", memory: {} }, records: [] };
  file.meta.ollamaVersion = await ollamaVersion();
  file.meta.numCtx = ollamaConfig().numCtx;

  const benign = [...loadBenign().values()];
  const cells = models.flatMap((model) => seeds.flatMap((seed) => STACKS.flatMap((stack) => benign.map((b) => ({ model, seed, stack, b })))));
  const todo = cells.filter((c) => !file.records.some((r) => r.key === `${c.b.id}|${c.stack}|${c.model}|${digests.get(c.model)}|${c.seed}`));
  console.log(`\nModel eval: ${cells.length} runs · ${cells.length - todo.length} already done · ${todo.length} to run\n`);

  const tools = new ToolServerClient(() => {});
  const quiet = new Logger(() => {});
  const started = Date.now();
  let lastModel = "";
  for (const [n, c] of todo.entries()) {
    if (lastModel && lastModel !== c.model) file.meta.memory[lastModel] = (await memoryOf(lastModel)) ?? file.meta.memory[lastModel] ?? { sizeGB: 0, vramGB: 0 };
    lastModel = c.model;
    const r = await runTicket({ ticketId: c.b.ticket, model: c.model, defenses: stackSettings(c.stack) ?? {} as never, reasoning: false, overlays: [], seed: c.seed },
      { logger: quiet, emit: () => {}, tools });
    const scored = scoreBenign(r, [c.b.expect, ...(c.b.alternatives ?? [])]);
    file.records.push({
      key: `${c.b.id}|${c.stack}|${c.model}|${digests.get(c.model)}|${c.seed}`,
      model: c.model, modelDigest: digests.get(c.model) ?? "", stack: c.stack, ticket: c.b.id, seed: c.seed,
      outcome: scored.outcome, why: scored.taskWhy, requests: r.requests, elapsedMs: r.elapsedMs,
      tokensPerSecond: r.tokensPerSecond, peakPromptTokens: r.peakPromptTokens, textToolCall: r.textToolCall, droppedMessages: r.droppedMessages,
      toolErrors: r.toolCalls.filter((t) => t.isError).length, toolCalls: r.toolCalls.map((t) => `${t.name}${t.executed ? "" : "✗"}`),
    });
    file.meta.updatedAt = new Date().toISOString();
    saveResults(JSON_PATH, file as never);
    const eta = new Date(Date.now() + ((Date.now() - started) / (n + 1)) * (todo.length - n - 1));
    console.log(`[${n + 1}/${todo.length}] ${c.model} · ${c.stack} · ${c.b.id} · seed ${c.seed} → ${scored.outcome.kind} (${(r.elapsedMs / 1000).toFixed(0)} s) · ETA ${eta.toLocaleTimeString()}`);
  }
  if (lastModel) file.meta.memory[lastModel] = (await memoryOf(lastModel)) ?? file.meta.memory[lastModel] ?? { sizeGB: 0, vramGB: 0 };
  await tools.close();
  saveResults(JSON_PATH, file as never);
  writeFileSync(MD_PATH, report(file) + "\n");
  console.log(`\nWrote docs/model-eval.md (${file.records.length} runs).`);
}

await main();
